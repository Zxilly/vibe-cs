const catalogs: Record<LanguagePreference, Catalog> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export function translate(locale: LanguagePreference, key: MessageKey): string {
  return catalogs[locale][key];
}

export type LiteralMessageKey = keyof typeof literalZhCN;

export function currentLocale(): LanguagePreference {
  return useUiStore.getState().language;
}

export function applyLocale(locale: LanguagePreference): boolean {
  if (currentLocale() === locale) return false;
  useUiStore.getState().setLanguage(locale);
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
  if (typeof window !== 'undefined') window.location.reload();
  return true;
}

export function msg(key: LiteralMessageKey, locale = currentLocale()): string {
  return locale === 'zh-CN' ? literalZhCN[key] : literalEnUS[key];
}

export function msgf(
  key: LiteralMessageKey,
  values: readonly (string | number | bigint | null | undefined)[],
  locale = currentLocale(),
): string {
  return msg(key, locale).replace(/\{(\d+)\}/g, (placeholder, index: string) => {
    const value = values[Number(index)];
    return value === undefined || value === null ? placeholder : String(value);
  });
}

export function useI18n() {
  const locale = useUiStore((state) => state.language);
  const t = useCallback((key: MessageKey) => translate(locale, key), [locale]);
  const text = useCallback((key: LiteralMessageKey) => msg(key, locale), [locale]);
  const format = useCallback(
    (key: LiteralMessageKey, values: readonly (string | number | bigint | null | undefined)[]) => msgf(key, values, locale),
    [locale],
  );
  return { locale, t, text, format };
}
